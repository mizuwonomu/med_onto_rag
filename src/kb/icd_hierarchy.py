def lookup_hierarchy(code: str) -> tuple[str | None, str | None]:
    match = _CODE_RE.match(code)
    if not match:
        return None, None

    letter, number_str = match.groups()
    number = int(number_str)

    for chapter, block, letter_range, low, high in _CHAPTERS:
        if letter == letter_range and low <= number <= high:
            return chapter, block

    return None, None
